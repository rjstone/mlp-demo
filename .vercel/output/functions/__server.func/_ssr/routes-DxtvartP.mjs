function infer(bits) {
	const contrib = new Array(8);
	const hidden = new Array(8);
	for (let j = 0; j < 8; j++) {
		let fromInputs = 0;
		let sum = b1[j];
		const row = w1[j];
		for (let i = 0; i < 20; i++) {
			const term = row[i] * bits[i];
			fromInputs += term;
			sum += term;
		}
		contrib[j] = fromInputs;
		hidden[j] = Math.tanh(sum);
	}
	let maxAbs = 0;
	for (const c of contrib) {
		const a = Math.abs(c);
		if (a > maxAbs) maxAbs = a;
	}
	const driven = contrib.map((c) => maxAbs > 1e-8 && Math.abs(c) >= .25 * maxAbs);
	const logits = new Array(11);
	for (let k = 0; k < 11; k++) {
		let sum = b2[k];
		const row = w2[k];
		for (let j = 0; j < 8; j++) sum += row[j] * hidden[j];
		logits[k] = sum;
	}
	let peak = logits[0];
	for (let k = 1; k < 11; k++) if (logits[k] > peak) peak = logits[k];
	const exps = logits.map((z) => Math.exp(z - peak));
	let total = 0;
	for (const e of exps) total += e;
	const probs = exps.map((e) => e / total);
	let winner = 0;
	for (let k = 1; k < 11; k++) if (probs[k] > probs[winner]) winner = k;
	return {
		contrib,
		driven,
		probs,
		winner
	};
}
