function fromBits(bits: number[]): string[] {
  const rows: string[] = [];
  for (let r = 0; r < 5; r++) {
    rows.push(
      bits
        .slice(r * 4, r * 4 + 4)
        .map((v) => (v ? "#" : "."))
        .join(""),
    );
  }
  return rows;
}

function unknownGlyphs(): string[][] {
  const taken = new Set(DIGITS.flat().map((rows) => rows.join("")));
  const out: string[][] = [];
  const add = (bits: number[]) => {
    const rows = fromBits(bits);
    const key = rows.join("");
    if (taken.has(key)) return;
    taken.add(key);
    out.push(rows);
  };

  add(Array(20).fill(0));
  add(Array(20).fill(1));
  for (let r = 0; r < 5; r++) {
    const bits = Array(20).fill(0);
    for (let c = 0; c < 4; c++) bits[r * 4 + c] = 1;
    add(bits);
  }
  for (let r0 = 0; r0 < 5; r0++) {
    for (let r1 = r0 + 1; r1 < 5; r1++) {
      const bits = Array(20).fill(0);
      for (const r of [r0, r1]) for (let c = 0; c < 4; c++) bits[r * 4 + c] = 1;
      add(bits);
    }
  }
  const checker = Array.from({ length: 20 }, (_, i) => ((i % 4) + Math.floor(i / 4)) % 2);
  add(checker);
  add(checker.map((v) => 1 - v));
  for (const diag of [0, 1]) {
    const bits = Array(20).fill(0);
    for (let r = 0; r < 5; r++) {
      const c = diag === 0 ? Math.min(3, r) : Math.max(0, 3 - r);
      bits[r * 4 + c] = 1;
    }
    add(bits);
  }
  return out;
}

